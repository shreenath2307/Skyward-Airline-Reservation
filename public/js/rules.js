/* "8 Golden Rules" tour — walks through Shneiderman's rules one by one and shows
   exactly where each is implemented (file:line from rules-data.js, generated by
   scripts/build-rules.js). Opened from the topbar button or /app.html#/...?rules=1 */
import { html, $ } from './util.js';
import { icon } from './icons.js';
import { openModal, toast } from './ui.js';
import { RULES } from './rules-data.js';

const TRY = {
  shortcuts: async () => (await import('./hci.js')).openShortcuts(),
  settings: () => $('#settingsBtn')?.click(),
  search: () => { const i = $('#pnrInput'); i?.focus(); i?.click(); },
  toast: () => toast('Flight 6E829 updated — changes saved.', 'success'),
  undo: () => toast('Demo: booking PNR1234 deleted (nothing was really deleted).', 'undo', 6000, { action: { label: 'Undo', onClick: () => toast('Restored — that is rule 6 in action.', 'success') } }),
  newRecord: async () => (await import('./forms.js')).createRecord('flights'),
};

function runTry(t) {
  const go = () => setTimeout(() => TRY[t.action]?.(), 350);
  if (t.route && location.hash.split('?')[0] !== t.route) {
    window.addEventListener('hashchange', go, { once: true });
    location.hash = t.route;
  } else go();
}

export function openRulesTour(start = 0) {
  if ($('.layer .rules-tour')) return;
  let i = Math.max(0, Math.min(RULES.length - 1, start));
  const m = openModal({
    eyebrow: 'HCI · Shneiderman', title: 'The 8 Golden Rules in Skyward', size: 'lg',
    subtitle: 'Step through each rule and see exactly where it lives in the code. Use ← → to move.',
    content: html`<div class="rules-tour" aria-live="polite"></div>`,
    footer: html`<button type="button" class="btn ghost" data-prev>${icon('arrowL', 18)}Previous</button>
      <span class="grow rules-count"></span>
      <button type="button" class="btn" data-try></button>
      <button type="button" class="btn primary" data-next></button>`,
  });
  const root = m.el;
  const body = root.querySelector('.rules-tour');

  const draw = () => {
    const r = RULES[i];
    body.innerHTML = String(html`
      <ol class="rules-dots" aria-label="Rules">${RULES.map((x, k) => html`<li><button type="button" class="${k === i ? 'on' : ''} ${k < i ? 'seen' : ''}" data-go="${k}" aria-label="Rule ${x.n}: ${x.title}" aria-current="${k === i ? 'step' : 'false'}">${x.n}</button></li>`)}</ol>
      <div class="rules-head"><span class="rules-num">${String(r.n).padStart(2, '0')}</span>
        <div><div class="eyebrow">Rule ${r.n} of ${RULES.length}</div><h3>${r.title}</h3><p class="rules-def">${r.def}</p></div></div>
      <h4 class="rules-sub">Where it is implemented</h4>
      <ul class="rules-list">${r.items.map((it) => html`<li><span class="rules-tick">${icon('check', 16)}</span><div><div>${it.text}</div>
        <div class="rules-where">${it.where.map((w) => html`<code>${w}</code>`)}</div></div></li>`)}</ul>`);
    root.querySelector('[data-prev]').disabled = i === 0;
    const next = root.querySelector('[data-next]');
    next.innerHTML = i === RULES.length - 1 ? `${icon('check', 18)}Done` : `Next rule${icon('arrowR', 18)}`;
    root.querySelector('[data-try]').innerHTML = `${icon('sparkle', 18)}Try it: ${r.try.label}`;
    root.querySelector('.rules-count').textContent = `${i + 1} / ${RULES.length}`;
  };
  const go = (k) => { i = Math.max(0, Math.min(RULES.length - 1, k)); draw(); };

  root.addEventListener('click', (e) => {
    const t = e.target.closest('[data-go],[data-prev],[data-next],[data-try]'); if (!t) return;
    if (t.hasAttribute('data-go')) go(Number(t.dataset.go));
    else if (t.hasAttribute('data-prev')) go(i - 1);
    else if (t.hasAttribute('data-next')) { if (i === RULES.length - 1) m.close(); else go(i + 1); }
    else if (t.hasAttribute('data-try')) { const tr = RULES[i].try; m.close(); runTry(tr); }
  });
  root.addEventListener('keydown', (e) => {
    if (e.target.closest('input,textarea,select')) return;
    if (e.key === 'ArrowRight') { e.preventDefault(); go(i + 1); }
    if (e.key === 'ArrowLeft') { e.preventDefault(); go(i - 1); }
  });
  draw();
  root.querySelector('[data-next]').focus();
  return m;
}

/* topbar button + deep link (?rules=1 or ?rules=N from the landing page) */
export function initRulesTour() {
  const b = $('#rulesBtn');
  if (b) { b.innerHTML = `${icon('star', 18)}<span>8 Rules</span>`; b.addEventListener('click', () => openRulesTour()); }
  document.addEventListener('keydown', (e) => {
    if (e.key !== '8' || e.ctrlKey || e.metaKey || e.altKey) return;
    const t = e.target; if (t && (t.isContentEditable || /^(INPUT|TEXTAREA|SELECT)$/.test(t.tagName))) return;
    e.preventDefault(); openRulesTour();
  });
  const m = location.hash.match(/[?&]rules=(\d+)/);
  if (m) {
    setTimeout(() => openRulesTour(Math.max(0, Number(m[1]) - 1)), 400);
    history.replaceState(null, '', location.hash.replace(/[?&]rules=\d+/, ''));
  }
}
